


//VARIABLES: es un espacio que guardamos en memoria. Se usa lowerCamelCase

// var. Puede cambiar la variable en el futuro, son globales.

var helloWorld = "¡Hola!"
console.log(helloWorld)

helloWorld = "¡Hola de nuevo!"
console.log(helloWorld)

// let: Solo son accesibles dentro de un bloque.

let helloWorld2 = "¡Hola 2!"
console.log(helloWorld2)

helloWorld2 = "¡Hola de nuevo2!"
console.log(helloWorld2)

// const: Valor que no puede ser reasignado 

const helloWorld3 = "¡Hola 3!"
console.log(helloWorld3)

